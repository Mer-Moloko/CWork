int main() {
    std::cout << "Сумма: " << 0.1 + 0.2 << std::endl; // На экране 0.3, но в памяти из-за двоичной арифметики хранится ~0.30000000000000004.
    std::cout << "Сумма равна 0.3? " << (0.1 + 0.2 == 0.3) << std::endl; // Вывело 0 (ложь), так как 0.30000000000000004 не равно точному 0.3.
    std::cout << "Треть: " << 1.0 / 3.0 << std::endl; // По умолчанию cout печатает 6 значащих цифр. «Хвост» не виден, так как cout автоматически округляет число до 6-й значащей цифры, чтобы не загромождать экран.
    return 0;
}