#include <iostream>

int main() {
    int a, b, c;
    std::cin >> a >> b >> c;

    // результат обрезается до целого (дробная часть отбрасывается): 13/3 = 4.
    std::cout << (a + b + c) / 3 << std::endl;    // целочисленное: 4

    // результат сохраняет дробную часть: 13/3.0 = 4.33333.
    std::cout << (a + b + c) / 3.0 << std::endl;  // дробное: 4.33333
}
